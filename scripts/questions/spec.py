"""
TripVibz city questions: the source of truth for what each city asks.

Each city has 5 questions, lead first (the lead becomes the city's share card).
Every question carries the searches people type for it (checked on Bing) and
the hashtags people post it under (checked on Instagram). See
scripts/questions/README.md for the research loop.

  q(prompt, options, place, searches, hashtags)
  keep=True on a question means: reword the existing row in place (same option
  ids, votes kept) instead of retiring it.
"""
SEASONS = ["Spring", "Summer", "Fall", "Winter"]


def q(prompt, options, place="Whole city", searches=(), tags=()):
    return {"prompt": prompt, "options": list(options), "place": place,
            "searches": list(searches), "tags": list(tags)}


def best_time(city, searches=None, tags=None, options=SEASONS):
    return q(f"Best time to visit {city}?", options, "Whole city",
             searches or [f"best time to visit {city.lower()}"],
             tags or [])


